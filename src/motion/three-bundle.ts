import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

// three.js ships as ES modules. Scene documents load every library as a
// plain script (modules would need cross-origin fetches from the sandboxed
// scene), so the core and the chosen add-ons are bundled into one script
// that sets window.THREE: rounded boxes, SVG shapes for extruded logos, a
// studio lighting environment and bloom post-processing.
//
// The bundle is generated ahead of time (npm run vendor:three) and committed
// as src/motion/vendor/three.js, so the studio and workers never run a
// compiler while serving scenes. A unit test regenerates it and fails when the
// committed file no longer matches the installed three.js.
export const THREE_BUNDLE_PATH = "src/motion/vendor/three.js";

const entry = `
import * as core from "three";
import { RoundedBoxGeometry } from "three/addons/geometries/RoundedBoxGeometry.js";
import { SVGLoader } from "three/addons/loaders/SVGLoader.js";
import { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";
import { EffectComposer } from "three/addons/postprocessing/EffectComposer.js";
import { RenderPass } from "three/addons/postprocessing/RenderPass.js";
import { UnrealBloomPass } from "three/addons/postprocessing/UnrealBloomPass.js";
import { OutputPass } from "three/addons/postprocessing/OutputPass.js";
import { BokehPass } from "three/addons/postprocessing/BokehPass.js";
window.THREE = Object.assign({}, core, { RoundedBoxGeometry, SVGLoader, RoomEnvironment, EffectComposer, RenderPass, UnrealBloomPass, OutputPass, BokehPass });
`;

export function buildThreeBundle(root = process.cwd()) {
  const esbuild = createRequire(path.join(root, "package.json"))(
    "esbuild",
  ) as typeof import("esbuild");
  const { version } = JSON.parse(
    readFileSync(path.join(root, "node_modules/three/package.json"), "utf8"),
  ) as { version: string };
  const result = esbuild.buildSync({
    stdin: { contents: entry, resolveDir: root, loader: "js" },
    bundle: true,
    format: "iife",
    minify: true,
    legalComments: "none",
    target: "es2020",
    write: false,
    logLevel: "silent",
    banner: {
      js: `/* three.js ${version} (MIT) with add-ons, generated by npm run vendor:three */`,
    },
  });
  return Buffer.from(result.outputFiles[0].contents);
}
